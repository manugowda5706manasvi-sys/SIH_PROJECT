def generate_docx(inspection_data: Dict[str, Any]) -> Optional[str]:
    """
    Generate an editable DOCX report and return the file path.
    """
    try:
        from docx import Document
        from docx.shared import Pt, RGBColor, Cm
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.oxml.ns import qn
        from docx.oxml import OxmlElement

        iid = inspection_data["inspection_id"]
        filename = f"report_{iid}.docx"
        filepath = os.path.join(REPORTS_DIR, filename)

        doc = Document()

        # Page margins
        section = doc.sections[0]
        section.top_margin = Cm(2)
        section.bottom_margin = Cm(2)
        section.left_margin = Cm(2.5)
        section.right_margin = Cm(2.5)

        # Title
        title = doc.add_heading("SMART-LM", level=0)
        title.alignment = WD_ALIGN_PARAGRAPH.CENTER
        sub = doc.add_paragraph("Smart Legal Metrology Compliance & Inspection System")
        sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
        sub.runs[0].font.size = Pt(11)
        sub.runs[0].font.color.rgb = RGBColor(0x4A, 0x55, 0x68)

        doc.add_paragraph("Government Prototype — SIH 2026 | SIH26034").alignment = WD_ALIGN_PARAGRAPH.CENTER
        doc.add_paragraph()

        # Disclaimer
        disc = doc.add_paragraph(
            "⚠ PROTOTYPE — NOT FOR ENFORCEMENT: This report is generated by an automated "
            "inspection assistance system. Results are NOT a substitute for official legal "
            "enforcement decisions. All findings must be verified by a qualified Legal "
            "Metrology Inspector before any enforcement action."
        )
        disc.runs[0].font.size = Pt(9)
        disc.runs[0].font.color.rgb = RGBColor(0x71, 0x80, 0x96)

        # Inspection Details
        doc.add_heading("Inspection Details", level=1)
        overall_status = inspection_data.get("overall_status", "NEEDS_HUMAN_REVIEW")
        table = doc.add_table(rows=6, cols=2)
        table.style = "Table Grid"
        rows_data = [
            ("Inspection ID", inspection_data.get("inspection_id", "—")),
            ("Date & Time", str(inspection_data.get("created_at", datetime.now()))[:19]),
            ("Product Name", inspection_data.get("product_name") or "Not detected"),
            ("Overall Status", overall_status.replace("_", " ")),
            ("Confidence", inspection_data.get("overall_confidence", "LOW")),
            ("Image Quality", inspection_data.get("image_quality", "—")),
        ]
        for i, (label, val) in enumerate(rows_data):
            row = table.rows[i]
            row.cells[0].text = label
            row.cells[0].paragraphs[0].runs[0].bold = True
            row.cells[1].text = str(val)
        doc.add_paragraph()

        # Declarations
        doc.add_heading("Extracted Declarations", level=1)
        declarations = inspection_data.get("declarations", [])
        if declarations:
            dtable = doc.add_table(rows=1 + len(declarations), cols=4)
            dtable.style = "Table Grid"
            hdr = dtable.rows[0].cells
            hdr[0].text = "Field"
            hdr[1].text = "Detected Value"
            hdr[2].text = "Confidence"
            hdr[3].text = "Status"
            for cell in hdr:
                cell.paragraphs[0].runs[0].bold = True
            for i, d in enumerate(declarations):
                row = dtable.rows[i + 1].cells
                row[0].text = (d.get("field_name") or "").replace("_", " ").title()
                row[1].text = (d.get("extracted_value") or "Not detected")[:100]
                row[2].text = d.get("confidence") or "LOW"
                row[3].text = (d.get("status") or "—").replace("_", " ")
        else:
            doc.add_paragraph("No declarations extracted.")
        doc.add_paragraph()

        # Violations
        violations = inspection_data.get("violations", [])
        doc.add_heading(f"Findings & Violations ({len(violations)})", level=1)
        if not violations:
            doc.add_paragraph("No violations or review items flagged.")
        else:
            vtable = doc.add_table(rows=1 + len(violations), cols=4)
            vtable.style = "Table Grid"
            vhdr = vtable.rows[0].cells
            vhdr[0].text = "Field"
            vhdr[1].text = "Reason"
            vhdr[2].text = "Severity"
            vhdr[3].text = "Rule ID"
            for cell in vhdr:
                cell.paragraphs[0].runs[0].bold = True
            for i, v in enumerate(violations):
                row = vtable.rows[i + 1].cells
                row[0].text = (v.get("field_name") or "").replace("_", " ").title()
                row[1].text = (v.get("reason") or "")[:200]
                row[2].text = v.get("severity") or "MEDIUM"
                row[3].text = v.get("rule_id") or "—"
        doc.add_paragraph()

        # Rule Reference
        doc.add_heading("Rule References (Prototype)", level=1)
        doc.add_paragraph(
            "Rules applied are prototype references based on the Legal Metrology "
            "(Packaged Commodities) Rules 2011 and amendments. All rules marked PROTOTYPE "
            "must be verified against current official Government of India Legal Metrology "
            "documents before enforcement use."
        )

        # Inspector Review Section
        doc.add_heading("Inspector Review", level=1)
        doc.add_paragraph("Inspector Name: ___________________________________")
        doc.add_paragraph()
        doc.add_paragraph("Inspector Designation: ___________________________")
        doc.add_paragraph()
        doc.add_paragraph("Date of Physical Inspection: _____________________")
        doc.add_paragraph()
        doc.add_paragraph("Inspector Remarks:")
        doc.add_paragraph()
        doc.add_paragraph("_" * 80)
        doc.add_paragraph("_" * 80)
        doc.add_paragraph()
        doc.add_paragraph("Signature & Stamp: ___________________________________")

        doc.save(filepath)
        logger.info("DOCX report generated: %s", filepath)
        return filepath

    except Exception as exc:
        logger.error("DOCX generation failed: %s", exc)
        return None
